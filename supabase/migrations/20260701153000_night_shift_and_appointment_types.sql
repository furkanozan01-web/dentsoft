CREATE TABLE IF NOT EXISTS public.appointment_types (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id BIGINT NOT NULL REFERENCES public.clinic_settings(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  default_duration SMALLINT NOT NULL DEFAULT 30 CHECK (default_duration BETWEEN 5 AND 1440),
  color TEXT NOT NULL DEFAULT '#CBD5E1' CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT true,
  is_system BOOLEAN NOT NULL DEFAULT false,
  branch_id BIGINT REFERENCES public.branches(id) ON DELETE SET NULL,
  doctor_ids BIGINT[] NOT NULL DEFAULT ARRAY[]::bigint[],
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(clinic_id, name)
);
CREATE INDEX IF NOT EXISTS appointment_types_clinic_active_idx ON public.appointment_types(clinic_id, is_active, name);
ALTER TABLE public.appointment_types ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS appointment_types_select ON public.appointment_types;
CREATE POLICY appointment_types_select ON public.appointment_types FOR SELECT TO authenticated USING (clinic_id = (SELECT public.get_my_clinic_id()));
DROP POLICY IF EXISTS appointment_types_manage ON public.appointment_types;
CREATE POLICY appointment_types_manage ON public.appointment_types FOR ALL TO authenticated
USING (clinic_id = (SELECT public.get_my_clinic_id()) AND EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = (SELECT auth.uid()) AND p.role IN ('admin','clinic_manager')))
WITH CHECK (clinic_id = (SELECT public.get_my_clinic_id()) AND EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = (SELECT auth.uid()) AND p.role IN ('admin','clinic_manager')));
GRANT SELECT, INSERT, UPDATE, DELETE ON public.appointment_types TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.appointment_types_id_seq TO authenticated;

