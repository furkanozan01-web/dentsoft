CREATE TABLE IF NOT EXISTS public.tariff_price_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id BIGINT NOT NULL REFERENCES public.clinic_settings(id) ON DELETE CASCADE,
  tariff_id BIGINT NOT NULL REFERENCES public.tariffs(id) ON DELETE CASCADE,
  old_price INTEGER NOT NULL,
  new_price INTEGER NOT NULL,
  change_rate NUMERIC(9,4) NOT NULL DEFAULT 0,
  effective_date DATE NOT NULL DEFAULT current_date,
  description TEXT,
  changed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS tariff_price_history_item_idx ON public.tariff_price_history(tariff_id, changed_at DESC);
ALTER TABLE public.tariff_price_history ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tariff_price_history_select ON public.tariff_price_history;
CREATE POLICY tariff_price_history_select ON public.tariff_price_history FOR SELECT TO authenticated
USING (clinic_id = (SELECT public.get_my_clinic_id()));

DROP POLICY IF EXISTS tariff_price_history_insert ON public.tariff_price_history;
CREATE POLICY tariff_price_history_insert ON public.tariff_price_history FOR INSERT TO authenticated
WITH CHECK (
  clinic_id = (SELECT public.get_my_clinic_id())
  AND EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = (SELECT auth.uid()) AND p.role IN ('admin','clinic_manager'))
);

GRANT SELECT, INSERT ON public.tariff_price_history TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.tariff_price_history_id_seq TO authenticated;

CREATE OR REPLACE FUNCTION public.capture_tariff_price_history()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
BEGIN
  IF NEW.price IS DISTINCT FROM OLD.price THEN
    NEW.price_updated_at := now();
    INSERT INTO public.tariff_price_history
      (clinic_id, tariff_id, old_price, new_price, change_rate, effective_date, description, changed_by)
    VALUES
      (NEW.clinic_id, NEW.id, OLD.price, NEW.price,
       CASE WHEN OLD.price = 0 THEN 0 ELSE ((NEW.price - OLD.price)::numeric / OLD.price) * 100 END,
       COALESCE(NULLIF(current_setting('app.tariff_effective_date', true), '')::date, current_date),
       NULLIF(current_setting('app.tariff_change_note', true), ''), auth.uid());
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS tariff_price_history_trigger ON public.tariffs;
CREATE TRIGGER tariff_price_history_trigger BEFORE UPDATE OF price ON public.tariffs
FOR EACH ROW EXECUTE FUNCTION public.capture_tariff_price_history();

CREATE OR REPLACE FUNCTION public.bulk_update_tariff_prices(
  p_profile_id BIGINT,
  p_tariff_ids BIGINT[],
  p_category TEXT,
  p_branch_id BIGINT,
  p_percent NUMERIC,
  p_rounding INTEGER,
  p_round_direction TEXT,
  p_vat_mode TEXT,
  p_effective_date DATE,
  p_description TEXT
) RETURNS INTEGER LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
DECLARE v_count INTEGER;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role IN ('admin','clinic_manager')) THEN
    RAISE EXCEPTION 'Yetkisiz erişim';
  END IF;
  IF abs(p_percent) > 1000 THEN RAISE EXCEPTION 'Yüzde oranı geçersiz'; END IF;
  PERFORM set_config('app.tariff_change_note', COALESCE(p_description, ''), true);
  PERFORM set_config('app.tariff_effective_date', COALESCE(p_effective_date, current_date)::text, true);

  UPDATE public.tariffs t SET
    price = CASE
      WHEN COALESCE(p_rounding, 0) <= 0 THEN round(t.price * (1 + p_percent / 100.0))::integer
      WHEN p_round_direction = 'up' THEN ceil((t.price * (1 + p_percent / 100.0)) / (p_rounding * 100.0))::integer * p_rounding * 100
      WHEN p_round_direction = 'down' THEN floor((t.price * (1 + p_percent / 100.0)) / (p_rounding * 100.0))::integer * p_rounding * 100
      ELSE round((t.price * (1 + p_percent / 100.0)) / (p_rounding * 100.0))::integer * p_rounding * 100
    END,
    vat_included = CASE WHEN p_vat_mode = 'included' THEN true WHEN p_vat_mode = 'excluded' THEN false ELSE t.vat_included END
  WHERE t.clinic_id = (SELECT public.get_my_clinic_id())
    AND t.profile_id = p_profile_id
    AND (COALESCE(array_length(p_tariff_ids, 1), 0) = 0 OR t.id = ANY(p_tariff_ids))
    AND (p_category IS NULL OR p_category = '' OR t.category = p_category)
    AND (p_branch_id IS NULL OR t.branch_id = p_branch_id);
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

REVOKE ALL ON FUNCTION public.bulk_update_tariff_prices(BIGINT,BIGINT[],TEXT,BIGINT,NUMERIC,INTEGER,TEXT,TEXT,DATE,TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.bulk_update_tariff_prices(BIGINT,BIGINT[],TEXT,BIGINT,NUMERIC,INTEGER,TEXT,TEXT,DATE,TEXT) TO authenticated;
