-- AI radiology decision-support foundations. Suggestions never become clinical records automatically.
ALTER TABLE public.patients DROP CONSTRAINT IF EXISTS patients_id_clinic_unique;
ALTER TABLE public.patients ADD CONSTRAINT patients_id_clinic_unique UNIQUE (id, clinic_id);
ALTER TABLE public.patient_images DROP CONSTRAINT IF EXISTS patient_images_id_clinic_unique;
ALTER TABLE public.patient_images ADD CONSTRAINT patient_images_id_clinic_unique UNIQUE (id, clinic_id);

CREATE TABLE public.image_ai_analyses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id BIGINT NOT NULL REFERENCES public.clinic_settings(id) ON DELETE CASCADE,
  patient_id BIGINT NOT NULL,
  image_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','completed','failed','reviewed')),
  model_name TEXT,
  model_version TEXT,
  summary TEXT,
  raw_result_json JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(raw_result_json) = 'object'),
  error_message TEXT,
  created_by UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  reviewed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  UNIQUE (id, clinic_id),
  FOREIGN KEY (patient_id, clinic_id) REFERENCES public.patients(id, clinic_id) ON DELETE CASCADE,
  FOREIGN KEY (image_id, clinic_id) REFERENCES public.patient_images(id, clinic_id) ON DELETE CASCADE,
  CHECK (status <> 'reviewed' OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);

CREATE TABLE public.image_ai_findings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id BIGINT NOT NULL REFERENCES public.clinic_settings(id) ON DELETE CASCADE,
  analysis_id BIGINT NOT NULL,
  patient_id BIGINT NOT NULL,
  image_id BIGINT NOT NULL,
  tooth_number SMALLINT CHECK (tooth_number IS NULL OR tooth_number BETWEEN 11 AND 85),
  finding_type TEXT NOT NULL CHECK (finding_type IN ('mandibular_nerve','maxillary_sinus','caries','missing_tooth','root_canal','implant','impacted_tooth','lesion','other')),
  confidence NUMERIC(5,4) CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1),
  description TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'suggested' CHECK (status IN ('suggested','accepted','rejected','edited')),
  linked_diagnosis_item_id BIGINT REFERENCES public.treatment_plan_items(id) ON DELETE SET NULL,
  reviewed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id, clinic_id),
  FOREIGN KEY (analysis_id, clinic_id) REFERENCES public.image_ai_analyses(id, clinic_id) ON DELETE CASCADE,
  FOREIGN KEY (patient_id, clinic_id) REFERENCES public.patients(id, clinic_id) ON DELETE CASCADE,
  FOREIGN KEY (image_id, clinic_id) REFERENCES public.patient_images(id, clinic_id) ON DELETE CASCADE,
  CHECK (status = 'suggested' OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);

CREATE TABLE public.image_ai_overlays (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id BIGINT NOT NULL REFERENCES public.clinic_settings(id) ON DELETE CASCADE,
  analysis_id BIGINT NOT NULL,
  image_id BIGINT NOT NULL,
  finding_id BIGINT,
  overlay_type TEXT NOT NULL CHECK (overlay_type IN ('mandibular_nerve','maxillary_sinus','caries','missing_tooth','root_canal','implant','impacted_tooth','lesion','other')),
  geometry_json JSONB NOT NULL CHECK (jsonb_typeof(geometry_json) = 'object'),
  color TEXT NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
  visible_default BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (analysis_id, clinic_id) REFERENCES public.image_ai_analyses(id, clinic_id) ON DELETE CASCADE,
  FOREIGN KEY (image_id, clinic_id) REFERENCES public.patient_images(id, clinic_id) ON DELETE CASCADE,
  FOREIGN KEY (finding_id, clinic_id) REFERENCES public.image_ai_findings(id, clinic_id) ON DELETE CASCADE
);

CREATE TABLE public.ai_treatment_plan_suggestions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id BIGINT NOT NULL REFERENCES public.clinic_settings(id) ON DELETE CASCADE,
  patient_id BIGINT NOT NULL,
  analysis_id BIGINT NOT NULL,
  title TEXT NOT NULL,
  plan_type TEXT NOT NULL CHECK (plan_type IN ('protective','surgical','prosthetic','economic','comprehensive')),
  status TEXT NOT NULL DEFAULT 'suggested' CHECK (status IN ('suggested','accepted','rejected','edited')),
  plan_items_json JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(plan_items_json) = 'array'),
  linked_treatment_plan_id BIGINT REFERENCES public.treatment_plans(id) ON DELETE SET NULL,
  created_by UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  accepted_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  accepted_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (patient_id, clinic_id) REFERENCES public.patients(id, clinic_id) ON DELETE CASCADE,
  FOREIGN KEY (analysis_id, clinic_id) REFERENCES public.image_ai_analyses(id, clinic_id) ON DELETE CASCADE,
  CHECK (status <> 'accepted' OR (accepted_by IS NOT NULL AND accepted_at IS NOT NULL))
);

CREATE INDEX image_ai_analyses_patient_idx ON public.image_ai_analyses(clinic_id, patient_id, created_at DESC);
CREATE INDEX image_ai_analyses_image_idx ON public.image_ai_analyses(clinic_id, image_id, created_at DESC);
CREATE INDEX image_ai_findings_analysis_idx ON public.image_ai_findings(clinic_id, analysis_id, status);
CREATE INDEX image_ai_overlays_analysis_idx ON public.image_ai_overlays(clinic_id, analysis_id, overlay_type);
CREATE INDEX ai_plan_suggestions_patient_idx ON public.ai_treatment_plan_suggestions(clinic_id, patient_id, status, created_at DESC);

CREATE OR REPLACE FUNCTION public.validate_image_ai_clinical_links()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
BEGIN
  IF TG_TABLE_NAME = 'image_ai_findings' AND NEW.linked_diagnosis_item_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.treatment_plan_items i JOIN public.treatment_plans p ON p.id = i.plan_id
    WHERE i.id = NEW.linked_diagnosis_item_id AND p.clinic_id = NEW.clinic_id AND p.patient_id = NEW.patient_id AND p.plan_type = 'diyagnoz'
  ) THEN RAISE EXCEPTION 'Linked diagnosis must belong to the same clinic and patient'; END IF;
  IF TG_TABLE_NAME = 'ai_treatment_plan_suggestions' AND NEW.linked_treatment_plan_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.treatment_plans p WHERE p.id = NEW.linked_treatment_plan_id AND p.clinic_id = NEW.clinic_id AND p.patient_id = NEW.patient_id
  ) THEN RAISE EXCEPTION 'Linked treatment plan must belong to the same clinic and patient'; END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER image_ai_findings_validate_link BEFORE INSERT OR UPDATE ON public.image_ai_findings FOR EACH ROW EXECUTE FUNCTION public.validate_image_ai_clinical_links();
CREATE TRIGGER ai_plan_suggestions_validate_link BEFORE INSERT OR UPDATE ON public.ai_treatment_plan_suggestions FOR EACH ROW EXECUTE FUNCTION public.validate_image_ai_clinical_links();

